def get_provider(spec: str | None = None) -> Provider:
    """Resolve a provider from a spec string or the environment.

    Default is `extractive` on purpose: the system must be runnable, testable,
    and evaluable with no model at all. Generation is an upgrade, not a
    prerequisite.
    """
    spec = spec or os.environ.get("DOF_QA_PROVIDER", "extractive")
    kind, _, arg = spec.partition(":")
    if kind == "extractive":
        return ExtractiveProvider()
    if kind == "ollama":
        return OllamaProvider(model=arg or "gemma4:12b")
    if kind == "anthropic":
        return AnthropicProvider(model=arg or "claude-opus-5")
    raise SystemExit(
        f"unknown provider {spec!r}; use extractive | ollama[:model] | anthropic[:model]"
    )


def _split_context(context: str) -> list[tuple[int, str]]:
    """Parse the context blocks that `answer.build_context` produced."""
    out: list[tuple[int, str]] = []
    for block in context.split("\n---\n"):
        block = block.strip()
        if not block.startswith("[nota codigo="):
            continue
        head, _, body = block.partition("]")
        code = head.removeprefix("[nota codigo=").split()[0]
        if code.isdigit():
            out.append((int(code), body.strip()))
    return out
